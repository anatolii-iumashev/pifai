export function isCrisis(text: string): boolean {
  return /(?:хочу|думаю|собираюсь|планирую|решил[аи]?)\s+(?:покончить с собой|умереть|суицид|убить себя)|(?:не хочу жить|порежу себя|причиню себе вред|самоповрежден|самоубийств)/iu.test(text);
}

